# Build the standalone script, validate it, then stage and publish the executable.
[CmdletBinding()]
param(
    [switch]$SkipCompile,
    [switch]$SkipTests,
    [string]$OutputPath,
    [string]$SourceOutputPath
)

$ErrorActionPreference = 'Stop'

function Assert-BuildScriptSyntax {
    param([string]$Text, [string]$Name = 'generated source')
    $tokens = $null
    $parseErrors = $null
    $ast = [System.Management.Automation.Language.Parser]::ParseInput($Text, [ref]$tokens, [ref]$parseErrors)
    if ($parseErrors.Count) {
        throw ("PowerShell syntax failed in {0}: {1}" -f $Name, (($parseErrors | ForEach-Object { "line $($_.Extent.StartLineNumber): $($_.Message)" }) -join '; '))
    }
    return $ast
}

function Get-BundledApplicationSource {
    param([Parameter(Mandatory = $true)][string]$ProjectRoot)
    $sourceRoot = Join-Path $ProjectRoot 'Source'
    $templatePath = Join-Path $sourceRoot 'App.ps1'
    $template = [IO.File]::ReadAllText($templatePath).Replace("`r`n", "`n")
    $marker = '# <BUNDLED_FUNCTIONS>'
    if ([regex]::Matches($template, [regex]::Escape($marker)).Count -ne 1) {
        throw 'Source/App.ps1 must contain exactly one # <BUNDLED_FUNCTIONS> marker.'
    }
    $parts = New-Object 'System.Collections.Generic.List[string]'
    foreach ($fileName in @('Services.ps1', 'Updates.ps1', 'Workflow.ps1', 'UI.ps1')) {
        $path = Join-Path $sourceRoot $fileName
        $text = [IO.File]::ReadAllText($path).Replace("`r`n", "`n")
        $ast = Assert-BuildScriptSyntax -Text $text -Name $fileName
        if (@($ast.EndBlock.Statements | Where-Object { $_ -isnot [System.Management.Automation.Language.FunctionDefinitionAst] }).Count) {
            throw "Source/$fileName must contain function definitions only; startup belongs in App.ps1."
        }
        $parts.Add(("# ---- Bundled from Source/{0} ----`n{1}" -f $fileName, $text.Trim()))
    }
    $result = $template.Replace($marker, ($parts -join "`n`n"))
    $result = "# Generated by Build.ps1 from Source/App.ps1 and Source service files. Edit Source/, then rebuild.`n" + $result
    $ast = Assert-BuildScriptSyntax -Text $result
    $duplicates = @($ast.EndBlock.Statements | Where-Object { $_ -is [System.Management.Automation.Language.FunctionDefinitionAst] } | Group-Object Name | Where-Object Count -gt 1)
    if ($duplicates.Count) { throw ('Duplicate bundled functions: ' + (($duplicates | ForEach-Object Name) -join ', ')) }
    return ($result.TrimEnd() + "`n")
}

function Get-BuildVersion {
    param([string]$SourceText)
    $matches = [regex]::Matches($SourceText, '(?m)^\$Global:ScriptVersion\s*=\s*"(\d+\.\d+\.\d+)"\s*$')
    if ($matches.Count -ne 1) { throw 'The application must declare one numeric major.minor.patch ScriptVersion.' }
    $version = [Version]$matches[0].Groups[1].Value
    if ($version.Major -gt 65534 -or $version.Minor -gt 65534 -or $version.Build -gt 65534) {
        throw 'A version component is too large for Windows executable metadata.'
    }
    return $version
}

function Write-BuildSource {
    param([string]$Text, [string]$Path)
    $absolutePath = [IO.Path]::GetFullPath($Path)
    $directory = [IO.Path]::GetDirectoryName($absolutePath)
    [IO.Directory]::CreateDirectory($directory) | Out-Null
    $temporaryPath = Join-Path $directory ('.qbitlauncher-source-' + [Guid]::NewGuid().ToString('N') + '.tmp')
    try {
        [IO.File]::WriteAllText($temporaryPath, $Text, (New-Object Text.UTF8Encoding($true)))
        if ([IO.File]::Exists($absolutePath)) { [IO.File]::Replace($temporaryPath, $absolutePath, [NullString]::Value, $true) }
        else { [IO.File]::Move($temporaryPath, $absolutePath) }
    }
    finally { if ([IO.File]::Exists($temporaryPath)) { [IO.File]::Delete($temporaryPath) } }
}

function Get-BuildFileHash {
    param([string]$Path)
    $algorithm = [Security.Cryptography.SHA256]::Create()
    $stream = [IO.File]::OpenRead($Path)
    try { return [BitConverter]::ToString($algorithm.ComputeHash($stream)).Replace('-', '').ToLowerInvariant() }
    finally { $stream.Dispose(); $algorithm.Dispose() }
}

function Install-BuildArtifact {
    param([string]$StagedPath, [string]$DestinationPath)
    $staged = [IO.Path]::GetFullPath($StagedPath)
    $destination = [IO.Path]::GetFullPath($DestinationPath)
    if (-not [IO.File]::Exists($staged) -or (Get-Item -LiteralPath $staged).Length -eq 0) {
        throw 'The staged build is missing or empty. The current executable has been preserved.'
    }
    foreach ($process in @(Get-Process -Name ([IO.Path]::GetFileNameWithoutExtension($destination)) -ErrorAction SilentlyContinue)) {
        $processPath = $null
        try { $processPath = $process.Path } catch { }
        if ($processPath -and [string]::Equals($processPath, $destination, [StringComparison]::OrdinalIgnoreCase)) {
            throw "Close the running application before replacing it: $destination"
        }
    }
    $backup = $null
    if ([IO.File]::Exists($destination)) {
        $backup = $destination + '.pre-build-' + (Get-Date -Format 'yyyyMMdd-HHmmss') + '-' + [Guid]::NewGuid().ToString('N').Substring(0, 8) + '.bak'
        [IO.File]::Replace($staged, $destination, $backup, $true)
    }
    else { [IO.File]::Move($staged, $destination) }
    return $backup
}

$projectRoot = $PSScriptRoot
if ([string]::IsNullOrWhiteSpace($SourceOutputPath)) { $SourceOutputPath = Join-Path $projectRoot 'qBitLauncher.ps1' }
if ([string]::IsNullOrWhiteSpace($OutputPath)) { $OutputPath = Join-Path $projectRoot 'qBitLauncher.exe' }
$SourceOutputPath = [IO.Path]::GetFullPath($SourceOutputPath)
$OutputPath = [IO.Path]::GetFullPath($OutputPath)
if ([string]::Equals($SourceOutputPath, $OutputPath, [StringComparison]::OrdinalIgnoreCase)) { throw 'The source and executable output paths must be different.' }
foreach ($inputName in @('App.ps1', 'Services.ps1', 'Updates.ps1', 'Workflow.ps1', 'UI.ps1')) {
    $inputPath = [IO.Path]::GetFullPath((Join-Path (Join-Path $projectRoot 'Source') $inputName))
    if ([string]::Equals($inputPath, $SourceOutputPath, [StringComparison]::OrdinalIgnoreCase) -or
        [string]::Equals($inputPath, $OutputPath, [StringComparison]::OrdinalIgnoreCase)) { throw 'Build outputs cannot overwrite development source files.' }
}

$sourceText = Get-BundledApplicationSource -ProjectRoot $projectRoot
$version = Get-BuildVersion -SourceText $sourceText
Write-BuildSource -Text $sourceText -Path $SourceOutputPath
Write-Host "Generated standalone source v$version at $SourceOutputPath"

$testsRun = 0
if (-not $SkipTests) {
    $testHost = Join-Path $env:WINDIR 'System32\WindowsPowerShell\v1.0\powershell.exe'
    foreach ($test in @(Get-ChildItem -LiteralPath (Join-Path $projectRoot 'Tests') -Filter 'Test-*.ps1' -File | Sort-Object Name)) {
        Write-Host "Running $($test.Name) in Windows PowerShell 5.1..."
        & $testHost -NoProfile -NonInteractive -ExecutionPolicy Bypass -File $test.FullName -SourcePath $SourceOutputPath
        if ($LASTEXITCODE -ne 0) { throw "Regression checks failed: $($test.Name) (exit $LASTEXITCODE). The current executable has been preserved." }
        $testsRun++
    }
}

if ($SkipCompile) {
    [pscustomobject]@{ Version = $version.ToString(); Source = $SourceOutputPath; TestsRun = $testsRun; Compiled = $false }
    return
}
if ($PSVersionTable.PSVersion.Major -ne 5) { throw 'Compile using Windows PowerShell 5.1: powershell.exe -NoProfile -File .\Build.ps1' }

$ps2exeVersion = '1.0.17'
try { Import-Module -Name ps2exe -RequiredVersion $ps2exeVersion -Force -ErrorAction Stop }
catch {
    Write-Host "Installing PS2EXE $ps2exeVersion for the current user..."
    Install-Module -Name ps2exe -RequiredVersion $ps2exeVersion -Scope CurrentUser -Repository PSGallery -Force -AllowClobber -ErrorAction Stop
    Import-Module -Name ps2exe -RequiredVersion $ps2exeVersion -Force -ErrorAction Stop
}

$outputDirectory = [IO.Path]::GetDirectoryName($OutputPath)
[IO.Directory]::CreateDirectory($outputDirectory) | Out-Null
$stageDirectory = Join-Path $outputDirectory ('.qbitlauncher-build-' + [Guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($stageDirectory) | Out-Null
# PS2EXE writes its DPI manifest through wildcard-aware Set-Content. Compile in
# a plain temporary directory, then copy to the destination's volume for the
# atomic replacement, so bracketed output folders are handled literally.
$compilerBase = [IO.Path]::GetFullPath([IO.Path]::GetTempPath())
if ($compilerBase.IndexOfAny([char[]]'[]*?') -ge 0) {
    throw 'The compiler temporary path contains wildcard characters. Set TEMP to a writable path without brackets before building.'
}
$compilerDirectory = Join-Path $compilerBase ('qbitlauncher-compiler-' + [Guid]::NewGuid().ToString('N'))
[IO.Directory]::CreateDirectory($compilerDirectory) | Out-Null
$backupPath = $null
try {
    $stagedExecutable = Join-Path $stageDirectory 'qBitLauncher.exe'
    $compiledExecutable = Join-Path $compilerDirectory 'qBitLauncher.exe'
    Invoke-ps2exe -inputFile $SourceOutputPath -outputFile $compiledExecutable -iconFile (Join-Path $projectRoot 'qBitLauncher Logo.ico') `
        -noConsole -STA -DPIAware -version ("{0}.{1}.{2}.0" -f $version.Major, $version.Minor, $version.Build) `
        -title 'qBitLauncher' -product 'qBitLauncher' -ErrorAction Stop
    if (-not [IO.File]::Exists($compiledExecutable)) { throw 'PS2EXE did not create an executable.' }
    $peHeader = [IO.File]::OpenRead($compiledExecutable)
    try { if ($peHeader.ReadByte() -ne 0x4d -or $peHeader.ReadByte() -ne 0x5a) { throw 'The staged output is not a Windows executable.' } }
    finally { $peHeader.Dispose() }
    [IO.File]::Copy($compiledExecutable, $stagedExecutable)
    $backupPath = Install-BuildArtifact -StagedPath $stagedExecutable -DestinationPath $OutputPath
    $releaseSource = Join-Path $outputDirectory 'qBitLauncher.ps1'
    if (-not [string]::Equals($releaseSource, $SourceOutputPath, [StringComparison]::OrdinalIgnoreCase)) { [IO.File]::Copy($SourceOutputPath, $releaseSource, $true) }
    $checksumPath = Join-Path $outputDirectory 'SHA256SUMS.txt'
    $checksumLines = @(
        ((Get-BuildFileHash -Path $OutputPath) + '  ' + [IO.Path]::GetFileName($OutputPath))
        ((Get-BuildFileHash -Path $releaseSource) + '  qBitLauncher.ps1')
    )
    [IO.File]::WriteAllLines($checksumPath, $checksumLines, (New-Object Text.UTF8Encoding($false)))
    [pscustomobject]@{ Version = $version.ToString(); Source = $SourceOutputPath; Executable = $OutputPath; Checksums = $checksumPath; Backup = $backupPath; TestsRun = $testsRun; Compiled = $true }
}
finally {
    $resolvedStage = [IO.Path]::GetFullPath($stageDirectory)
    $resolvedOutput = [IO.Path]::GetFullPath($outputDirectory).TrimEnd([char]92) + [IO.Path]::DirectorySeparatorChar
    if ($resolvedStage.StartsWith($resolvedOutput, [StringComparison]::OrdinalIgnoreCase) -and
        [IO.Path]::GetFileName($resolvedStage).StartsWith('.qbitlauncher-build-') -and [IO.Directory]::Exists($resolvedStage)) {
        Remove-Item -LiteralPath $resolvedStage -Recurse -Force
    }
    $resolvedCompiler = [IO.Path]::GetFullPath($compilerDirectory)
    if ($resolvedCompiler.StartsWith($compilerBase, [StringComparison]::OrdinalIgnoreCase) -and
        [IO.Path]::GetFileName($resolvedCompiler).StartsWith('qbitlauncher-compiler-') -and [IO.Directory]::Exists($resolvedCompiler)) {
        Remove-Item -LiteralPath $resolvedCompiler -Recurse -Force
    }
}
